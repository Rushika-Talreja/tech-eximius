def load_detector_metadata() -> dict[str, dict[str, Any]]:
    """
    Loads detector mappings.
    Checks packages/auditor_core/rag/detector_map.yaml first if present (read-only);
    falls back to detectors/severity_defaults.yaml.
    """
    current_dir = Path(__file__).resolve().parent
    repo_root = current_dir.parents[3]  # root of workspace
    rag_map_file = repo_root / "packages" / "auditor_core" / "rag" / "detector_map.yaml"
    defaults_file = current_dir / "severity_defaults.yaml"

    meta: dict[str, dict[str, Any]] = {}
    if defaults_file.exists():
        with open(defaults_file, "r") as f:
            meta.update(yaml.safe_load(f) or {})

    if rag_map_file.exists():
        try:
            with open(rag_map_file, "r") as f:
                rag_meta = yaml.safe_load(f) or {}
                # Merge rag metadata on top of defaults
                for k, v in rag_meta.items():
                    if k in meta:
                        meta[k].update(v)
                    else:
                        meta[k] = v
        except Exception:
            pass

    return meta


@dataclass
class CandidateEvidence:
    kind: str
    title: str
    locator: str | None = None
    source_url: str | None = None
    quote: str | None = None
    retrieval_score: float | None = None
    facts: dict[str, Any] = field(default_factory=dict)


@dataclass
class CandidateFinding:
    id: uuid.UUID
    source: str
    detector: str
    category: str
    title: str
    severity: str
    confidence: float
    file_path: str
    start_line: int
    end_line: int
    description: str
    scenario: str | None = None
    status: str = "open"
    scored: bool = True
    evidence: list[CandidateEvidence] = field(default_factory=list)
    function_signature: str | None = None


def is_dependency_or_test_file(path: str) -> bool:
    """Returns True if file is inside a vendor/test folder."""
    p = path.lower().replace("\\", "/")
    patterns = [
        "node_modules/",
        "lib/",
        "/lib/",
        "test/",
        "/test/",
        "tests/",
        "/tests/",
        "mock/",
        "/mock/",
        "mocks/",
        "/mocks/",
    ]
    return any(pat in p for pat in patterns)


def run_slither_curated_scan(
    sources: dict[str, str],
    solc_version: str = "0.8.24",
    metadata_map: dict[str, dict[str, Any]] | None = None,
) -> list[CandidateFinding]:
    """
    Runs curated Slither detectors inside a sandbox tempdir.
    """
    if metadata_map is None:
        metadata_map = load_detector_metadata()

    # Find solc binary
    try:
        solc_bin = locate_solc_binary(solc_version)
    except Exception:
        solc_bin = None

    repo_root = Path(__file__).resolve().parents[4]
    venv_path = repo_root / ".venv"
    slither_bin = venv_path / "bin" / "slither"
    if not slither_bin.exists():
        # Fall back to PATH slither if .venv doesn't have it
        slither_bin = Path("slither")

    candidates: list[CandidateFinding] = []

    with tempfile.TemporaryDirectory() as tmpdir:
        # Write files
        for rel_path, content in sources.items():
            fpath = Path(tmpdir) / rel_path
            fpath.parent.mkdir(parents=True, exist_ok=True)
            fpath.write_text(content, encoding="utf-8")

        # Set up sandbox env
        env = dict(os.environ)
        if venv_path.exists():
            env["VIRTUAL_ENV"] = str(venv_path)

        detectors_arg = ",".join(CURATED_SLITHER_DETECTORS)

        for rel_path in sources.keys():
            if not rel_path.endswith(".sol"):
                continue
            target_path = Path(tmpdir) / rel_path

            cmd = [
                str(slither_bin),
                str(target_path),
                "--json", "-",
                "--detect", detectors_arg,
            ]
            if solc_bin and Path(solc_bin).exists():
                cmd.extend(["--solc", str(solc_bin)])

            try:
                proc = subprocess.run(
                    cmd,
                    capture_output=True,
                    text=True,
                    cwd=tmpdir,
                    env=env,
                    timeout=30,
                )
                if not proc.stdout:
                    continue
                try:
                    data = json.loads(proc.stdout)
                except Exception:
                    continue

                raw_findings = data.get("results", {}).get("detectors", [])
                for rf in raw_findings:
                    check_id = rf.get("check", "")
                    if check_id not in CURATED_SLITHER_DETECTORS:
                        continue

                    meta = metadata_map.get(check_id, {})
                    title = meta.get("title", rf.get("description", check_id).split("\n")[0])
                    severity = meta.get("default_severity", rf.get("impact", "medium").lower())
                    confidence = float(meta.get("default_confidence", 0.80))

                    # Parse elements to find span and function
                    elements = rf.get("elements", [])
                    fn_sig: str | None = None
                    file_p = rel_path
                    start_l = 1
                    end_l = 1
                    facts_dict: dict[str, Any] = {"slither_check": check_id}

                    for el in elements:
                        s_map = el.get("source_mapping", {})
                        lines = s_map.get("lines", [])
                        if lines and start_l == 1 and end_l == 1:
                            start_l = lines[0]
                            end_l = lines[-1]
                        fn_fields = el.get("type_specific_fields", {})
                        if "signature" in fn_fields and not fn_sig:
                            fn_sig = fn_fields["signature"]

                    desc = rf.get("description", title).strip()
                    loc = f"{file_p}:{start_l}"
                    finding_id = uuid.uuid4()

                    ev = CandidateEvidence(
                        kind="static_fact",
                        title=f"Slither: {check_id}",
                        locator=loc,
                        source_url=rf.get("reference"),
                        facts=facts_dict,
                    )

                    candidates.append(CandidateFinding(
                        id=finding_id,
                        source="slither",
                        detector=check_id,
                        category="security",
                        title=title,
                        severity=severity,
                        confidence=confidence,
                        file_path=file_p,
                        start_line=start_l,
                        end_line=end_l,
                        description=desc,
                        scenario=None,
                        status="open",
                        scored=True,
                        evidence=[ev],
                        function_signature=fn_sig,
                    ))

            except Exception:
                # If Slither fails or times out, continue
                continue

    return candidates


def run_custom_detectors(
    contracts: dict[str, ContractSemanticModel],
    missing_access_control_candidates: list[dict[str, Any]],
    metadata_map: dict[str, dict[str, Any]] | None = None,
) -> list[CandidateFinding]:
    """
    Runs the 3 custom detectors:
      1. unprotected-privileged-write (from M2 facts)
      2. unbounded-mint
      3. missing-initializer-guard
    """
    if metadata_map is None:
        metadata_map = load_detector_metadata()

    findings: list[CandidateFinding] = []

    # 1. unprotected-privileged-write
    unprot_meta = metadata_map.get("unprotected-privileged-write", {
        "title": "Unprotected Privileged State Change",
        "default_severity": "high",
        "default_confidence": 0.95,
    })
    for item in missing_access_control_candidates:
        c_name = item.get("contract", "")
        fn_sig = item.get("function_signature", "")
        span = item.get("span", {})
        file_path = span.get("file", "src/Contract.sol")
        start_line = span.get("start_line", 1)
        end_line = span.get("end_line", 1)
        power_cat = item.get("power_category", "STATE_WRITE")

        finding_id = uuid.uuid4()
        locator = f"{file_path}:{start_line}"
        desc = (
            f"Function `{fn_sig}` in `{c_name}` performs privileged state writes "
            f"({power_cat}) without access control modifiers or caller validation."
        )

        ev = CandidateEvidence(
            kind="static_fact",
            title=f"Custom: unprotected-privileged-write ({power_cat})",
            locator=locator,
            facts={
                "contract": c_name,
                "function": fn_sig,
                "power_category": power_cat,
                "state_writes": item.get("state_writes", []),
            },
        )

        findings.append(CandidateFinding(
            id=finding_id,
            source="custom_detector",
            detector="unprotected-privileged-write",
            category="security",
            title=unprot_meta.get("title", "Unprotected Privileged State Change"),
            severity=unprot_meta.get("default_severity", "high"),
            confidence=float(unprot_meta.get("default_confidence", 0.95)),
            file_path=file_path,
            start_line=start_line,
            end_line=end_line,
            description=desc,
            scenario=f"An arbitrary caller can call `{fn_sig}` and modify sensitive contract state.",
            status="open",
            scored=True,
            evidence=[ev],
            function_signature=fn_sig,
        ))

    # 2. unbounded-mint & 3. missing-initializer-guard
    mint_meta = metadata_map.get("unbounded-mint", {
        "title": "Unbounded Token Minting",
        "default_severity": "high",
        "default_confidence": 0.90,
    })
    init_meta = metadata_map.get("missing-initializer-guard", {
        "title": "Missing Initializer Reentrancy/Access Guard",
        "default_severity": "high",
        "default_confidence": 0.85,
    })

    for c_name, model in contracts.items():
        c_dict = model.model_dump()
        c_file = model.metadata.get("spans", {}).get("file")

        for fn in model.functions:
            fn_dict = fn.model_dump()
            fn_file = fn.span.file or c_file or "src/Contract.sol"

            # Check 2: unbounded-mint
            # Function mints tokens if it calls _mint or has MINT power category or writes totalSupply
            is_mint = (
                any(tf.get("flow_type") == "mint" for tf in fn_dict.get("token_flows", []))
                or "_mint(" in fn.body_source
                or "totalSupply +=" in fn.body_source
                or "totalSupply = totalSupply +" in fn.body_source
            )
            if is_mint:
                cap_info = detect_cap(fn_dict, c_dict)
                if not cap_info:
                    f_id = uuid.uuid4()
                    loc = f"{fn_file}:{fn.span.start_line}"
                    desc = (
                        f"Function `{fn.signature}` in `{c_name}` increases token supply "
                        f"without an enforced upper bound or cap."
                    )
                    ev = CandidateEvidence(
                        kind="static_fact",
                        title="Custom: unbounded-mint",
                        locator=loc,
                        facts={"contract": c_name, "function": fn.signature, "cap_detected": False},
                    )
                    findings.append(CandidateFinding(
                        id=f_id,
                        source="custom_detector",
                        detector="unbounded-mint",
                        category="security",
                        title=mint_meta.get("title", "Unbounded Token Minting"),
                        severity=mint_meta.get("default_severity", "high"),
                        confidence=float(mint_meta.get("default_confidence", 0.90)),
                        file_path=fn_file,
                        start_line=fn.span.start_line,
                        end_line=fn.span.end_line,
                        description=desc,
                        scenario=f"Authorized or unauthorized callers could inflate token supply without restriction.",
                        status="open",
                        scored=True,
                        evidence=[ev],
                        function_signature=fn.signature,
                    ))

            # Check 3: missing-initializer-guard
            # Detect initialize functions lacking initializer modifier/guard
            is_init_func = (
                fn.name.lower() in ("initialize", "init")
                or fn.name.lower().startswith("initialize_")
            )
            if is_init_func:
                mod_names = [m.lower() for m in fn.modifiers]
                has_init_modifier = any(
                    m in ("initializer", "reinitializer", "onlyinitializing")
                    for m in mod_names
                )
                body = fn.body_source
                has_body_guard = (
                    "require(!initialized" in body.replace(" ", "")
                    or "require(!_initialized" in body.replace(" ", "")
                    or "if(initialized)revert" in body.replace(" ", "")
                    or "if(_initialized)revert" in body.replace(" ", "")
                )
                if not has_init_modifier and not has_body_guard:
                    f_id = uuid.uuid4()
                    loc = f"{fn_file}:{fn.span.start_line}"
                    desc = (
                        f"Initialization function `{fn.signature}` in `{c_name}` does not have "
                        f"an `initializer` modifier or initialization flag check."
                    )
                    ev = CandidateEvidence(
                        kind="static_fact",
                        title="Custom: missing-initializer-guard",
                        locator=loc,
                        facts={"contract": c_name, "function": fn.signature, "modifiers": fn.modifiers},
                    )
                    findings.append(CandidateFinding(
                        id=f_id,
                        source="custom_detector",
                        detector="missing-initializer-guard",
                        category="security",
                        title=init_meta.get("title", "Missing Initializer Reentrancy/Access Guard"),
                        severity=init_meta.get("default_severity", "high"),
                        confidence=float(init_meta.get("default_confidence", 0.85)),
                        file_path=fn_file,
                        start_line=fn.span.start_line,
                        end_line=fn.span.end_line,
                        description=desc,
                        scenario=f"An attacker can re-call `{fn.signature}` to take over contract ownership or state.",
                        status="open",
                        scored=True,
                        evidence=[ev],
                        function_signature=fn.signature,
                    ))

    return findings


def convert_privilege_candidates_to_findings(
    candidates: list[dict[str, Any]],
    metadata_map: dict[str, dict[str, Any]] | None = None,
) -> list[CandidateFinding]:
    """
    Converts PrivilegeCandidate objects (high/critical unmitigated results)
    into findings with source='privilege_map' and static_fact evidence.
    """
    if metadata_map is None:
        metadata_map = load_detector_metadata()

    findings: list[CandidateFinding] = []
    priv_meta = metadata_map.get("privilege-escalation", {
        "title": "Unmitigated Privileged Centralization Risk",
        "default_severity": "high",
        "default_confidence": 0.95,
    })

    for cand in candidates:
        r_key = cand.get("role_key", "UNKNOWN")
        power_cat = cand.get("power_category", "PRIVILEGED_ACTION")
        tier = cand.get("tier", "high")
        blast = cand.get("blast_score", 70)
        c_name = cand.get("contract", "")
        fn_sig = cand.get("function_signature", "")
        facts = cand.get("facts", {})

        file_path = facts.get("file_path") or facts.get("span", {}).get("file") or "src/Contract.sol"
        start_line = facts.get("start_line") or facts.get("span", {}).get("start_line", 1)
        end_line = facts.get("end_line") or facts.get("span", {}).get("end_line", 1)

        f_id = uuid.uuid4()
        title = f"Privilege Centralization: {r_key} has unmitigated {power_cat}"
        desc = cand.get("reason") or (
            f"Role {r_key} holds unmitigated authority to execute {power_cat} "
            f"via `{fn_sig}` in `{c_name}` with blast score {blast}."
        )

        ev = CandidateEvidence(
            kind="static_fact",
            title=f"Privilege Map: {r_key} -> {power_cat}",
            locator=f"{file_path}:{start_line}",
            facts=facts,
        )

        findings.append(CandidateFinding(
            id=f_id,
            source="privilege_map",
            detector="privilege-escalation",
            category="security",
            title=title,
            severity=tier,
            confidence=float(priv_meta.get("default_confidence", 0.95)),
            file_path=file_path,
            start_line=start_line,
            end_line=end_line,
            description=desc,
            scenario=f"Compromise of {r_key} key permits immediate unmitigated execution of {power_cat}.",
            status="open",
            scored=True,
            evidence=[ev],
            function_signature=fn_sig,
        ))

    return findings


def deduplicate_and_filter_findings(
    candidates: list[CandidateFinding],
    include_dependencies: bool = False,
) -> list[CandidateFinding]:
    """
    Deduplicates candidates by (detector, file_path, function_signature or start_line).
    Filters out dependencies and test files unless include_dependencies is True.
    """
    severity_order = {"critical": 4, "high": 3, "medium": 2, "low": 1, "info": 0}
    seen: dict[tuple[str, str, str], CandidateFinding] = {}

    for cand in candidates:
        if not include_dependencies and is_dependency_or_test_file(cand.file_path):
            continue

        fn_key = cand.function_signature or str(cand.start_line)
        key = (cand.detector, cand.file_path, fn_key)

        if key not in seen:
            seen[key] = cand
        else:
            existing = seen[key]
            # Keep higher severity or higher confidence
            if severity_order.get(cand.severity.lower(), 0) > severity_order.get(existing.severity.lower(), 0):
                seen[key] = cand
            elif (
                severity_order.get(cand.severity.lower(), 0) == severity_order.get(existing.severity.lower(), 0)
                and cand.confidence > existing.confidence
            ):
                seen[key] = cand

    return list(seen.values())


async def run_scanning_stage(
    audit_id: uuid.UUID,
    org_id: uuid.UUID,
    session: Any,
    sources: dict[str, str],
    solc_version: str,
    models: dict[str, ContractSemanticModel],
    missing_ac: list[dict[str, Any]],
    privilege_candidates: list[dict[str, Any]],
    options: dict[str, Any],
) -> list[CandidateFinding]:
    """
    Stage 4: Scanning.
    Runs curated Slither + custom detectors + maps privilege candidates.
    Persists findings and finding_evidence rows to DB.
    """
    from sqlalchemy import select, delete
    from app.db import AuditFile, Finding, FindingEvidence, validate_finding_has_evidence

    # Load file mapping
    file_rows = (await session.execute(
        select(AuditFile).where(AuditFile.audit_id == audit_id)
    )).scalars().all()
    file_ids_by_path = {f.path: f.id for f in file_rows}

    # 1. Run Slither curated scan
    slither_cands = run_slither_curated_scan(sources, solc_version=solc_version)

    # 2. Run custom detectors
    custom_cands = run_custom_detectors(models, missing_ac)

    # 3. Convert privilege candidates
    priv_cands = convert_privilege_candidates_to_findings(privilege_candidates)

    # 4. Deduplicate & filter dependencies
    all_cands = slither_cands + custom_cands + priv_cands
    include_deps = bool(options.get("include_dependencies", False))
    filtered_cands = deduplicate_and_filter_findings(all_cands, include_dependencies=include_deps)

    # 5. Clean up existing findings for idempotency
    await session.execute(delete(Finding).where(Finding.audit_id == audit_id))

    # 6. Persist findings and evidence
    for cand in filtered_cands:
        matching_file_id = file_ids_by_path.get(cand.file_path)
        if not matching_file_id:
            for p, fid in file_ids_by_path.items():
                if p.endswith(cand.file_path) or cand.file_path.endswith(p):
                    matching_file_id = fid
                    break
        if not matching_file_id and file_rows:
            matching_file_id = file_rows[0].id

        f_db = Finding(
            id=cand.id,
            audit_id=audit_id,
            org_id=org_id,
            source=cand.source,
            detector=cand.detector,
            category=cand.category,
            title=cand.title,
            severity=cand.severity.lower(),
            confidence=cand.confidence,
            file_id=matching_file_id,
            start_line=cand.start_line,
            end_line=cand.end_line,
            description=cand.description,
            scenario=cand.scenario,
            status=cand.status,
            scored=cand.scored,
        )

        db_evidences: list[FindingEvidence] = []
        for ev in cand.evidence:
            ev_db = FindingEvidence(
                id=uuid.uuid4(),
                finding_id=cand.id,
                org_id=org_id,
                kind=ev.kind,
                title=ev.title,
                source_url=ev.source_url,
                locator=ev.locator,
                quote=ev.quote,
                retrieval_score=ev.retrieval_score,
                facts=ev.facts,
            )
            db_evidences.append(ev_db)

        # Service layer enforcement
        validate_finding_has_evidence(f_db, db_evidences)

        session.add(f_db)
        for ev_db in db_evidences:
            session.add(ev_db)

    await session.commit()
    return filtered_cands


def build_coverage_statement(
    file_paths: list[str],
    contract_names: list[str],
    not_analyzed_items: list[Any],
) -> dict[str, Any]:
    """
    Constructs the canonical coverage statement.
    """
    detectors_run = list(CURATED_SLITHER_DETECTORS) + [
        "unprotected-privileged-write",
        "unbounded-mint",
        "missing-initializer-guard",
        "privilege-escalation",
    ]

    formatted_not_analyzed: list[dict[str, Any]] = []
    for item in not_analyzed_items:
        if isinstance(item, str):
            formatted_not_analyzed.append({"reason": item})
        elif isinstance(item, dict):
            formatted_not_analyzed.append(item)

    return {
        "analyzed": {
            "files": sorted(file_paths),
            "contracts": sorted(contract_names),
            "detectors_run": detectors_run,
        },
        "not_analyzed": formatted_not_analyzed,
        "out_of_scope": [
            "economic design",
            "oracle trust",
            "governance",
            "off-chain components",
            "deployment configuration",
            "key custody",
        ],
    }

