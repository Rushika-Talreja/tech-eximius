"""
Detector scanner engine for Stage 4 (Scanning).
Runs curated Slither detectors + 3 custom detectors:
  1. unprotected-privileged-write
  2. unbounded-mint
  3. missing-initializer-guard
Converts PrivilegeCandidate (high/critical unmitigated) to findings with source=privilege_map.
Deduplicates findings by (detector class/check, function/span).
Filters dependencies/tests unless include_dependencies is True.
Enforces static_fact evidence for every candidate.
"""
